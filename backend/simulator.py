def format_minute(minute: int) -> str:
    """Render an integer minute offset as a ``HH:MM`` wall clock label."""
    absolute = BASE_MINUTE + int(round(minute))
    return f"{absolute // 60:02d}:{absolute % 60:02d}"


def format_delay(minute: int) -> str:
    """Render an integer delay in a dispatcher friendly way."""
    if minute <= 0:
        return "on time"
    return f"+{minute} min"


def run_minutes(train_id: str, block_id: str) -> int:
    return TRAIN_BY_ID[train_id]["run_min"][block_id]


def final_arrival(entries_for_train: Dict[str, int], train_id: str) -> int:
    """Arrival at the terminus implied by a train's block entry times."""
    last_block = ROUTE_BLOCK_IDS[-1]
    return entries_for_train[last_block] + run_minutes(train_id, last_block)


