def schedule_from_entries(
    block_entries: Dict[str, Dict[str, int]],
    source: str,
    baseline_entries: Optional[Dict[str, Dict[str, int]]] = None,
) -> Dict[str, Any]:
    """Expand raw ``{train: {block: entry}}`` data into the API schedule shape.

    The payload contains, per train, the occupancy of every block, the arrival /
    departure at every station, the delay of every movement versus the booked
    timetable and the resulting headline numbers used by the KPI cards.
    """
    trains_payload: Dict[str, Any] = {}
    total_delay = 0
    max_delay = 0

    for train in TRAINS:
        train_id = train["id"]
        entries = block_entries[train_id]
        booked = baseline_entries[train_id] if baseline_entries else None

        blocks_payload: Dict[str, Any] = {}
        for block_id in ROUTE_BLOCK_IDS:
            entry = entries[block_id]
            exit_ = entry + run_minutes(train_id, block_id)
            blocks_payload[block_id] = {
                "block_id": block_id,
                "entry": entry,
                "exit": exit_,
                "entry_label": format_minute(entry),
                "exit_label": format_minute(exit_),
                "run_min": run_minutes(train_id, block_id),
                "delay": (entry - booked[block_id]) if booked else 0,
            }

        stations_payload: Dict[str, Any] = {}
        for index, station in enumerate(STATIONS):
            station_id = station["id"]
            if index == 0:
                arrive = depart = entries[ROUTE_BLOCK_IDS[0]]
            elif index == len(STATIONS) - 1:
                arrive = depart = final_arrival(entries, train_id)
            else:
                upstream_block = ROUTE_BLOCK_IDS[index - 1]
                arrive = entries[upstream_block] + run_minutes(train_id, upstream_block)
                depart = entries[ROUTE_BLOCK_IDS[index]]
            dwell = depart - arrive
            planned_dwell = train["dwell_min"].get(station_id, 0)
            stations_payload[station_id] = {
                "station_id": station_id,
                "arrive": arrive,
                "depart": depart,
                "arrive_label": format_minute(arrive),
                "depart_label": format_minute(depart),
                "dwell_min": dwell,
                "planned_dwell_min": planned_dwell,
                "hold_min": max(0, dwell - planned_dwell),
            }

        arrival = final_arrival(entries, train_id)
        booked_arrival = final_arrival(booked, train_id) if booked else arrival
        delay = arrival - booked_arrival
        total_delay += delay
        max_delay = max(max_delay, delay)

        trains_payload[train_id] = {
            "train_id": train_id,
            "name": train["name"],
            "type": train["type"],
            "priority": train["priority"],
            "weight": train["weight"],
            "colour": train["colour"],
            "blocks": blocks_payload,
            "stations": stations_payload,
            "final_arrival": arrival,
            "final_arrival_label": format_minute(arrival),
            "booked_arrival": booked_arrival,
            "booked_arrival_label": format_minute(booked_arrival),
            "final_delay": delay,
            "final_delay_label": format_delay(delay),
        }

    return {
        "source": source,
        "totals": {
            "total_delay_min": total_delay,
            "max_delay_min": max_delay,
            "trains": len(TRAINS),
        },
        "trains": trains_payload,
        "notes": [],
    }

