"""Railway simulation core for the AI train traffic control prototype.

Time model
----------
Every timestamp in this module is an **integer number of minutes measured from**
``BASE_MINUTE`` (10:00 local time).  :func:`format_minute` converts such a value
back into a human readable ``HH:MM`` label for the API / UI layer.

What lives here
---------------
1. The topology of the single corridor prototype (stations, blocks, trains).
2. The *booked* baseline timetable, generated by the rule based planner
   :func:`plan_rule_based` so that the booked plan is guaranteed conflict free.
3. The disruption model:

   * :func:`propagate_legacy` -- the legacy single hop delay propagation rule
     that represents "what happens if the dispatcher does not intervene":
     the disrupted train and the *immediate* follower inherit a linear shift
     while trains further downstream are missed, which leaves real conflicts.
   * :func:`plan_rule_based` -- the same rule engine but with every physical
     constraint enforced (first come first served with clamps).  This is the
     fallback plan the CP-SAT optimizer is benchmarked against.

Disclaimer
----------
Decision-support / simulation prototype.  It never issues movement authorities
to real trains -- every resume signal is a recommendation for a human dispatcher.
"""

