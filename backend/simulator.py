def normalise_disruption(raw: Dict[str, Any]) -> Dict[str, Any]:
    """Validate and normalise an incoming disruption request.

    Two disruption kinds are supported:

    ``signal_delay``
        ``{"type": "signal_delay", "train_id": "T204", "block_id": "BL2",
        "minutes": 15}`` -- the train may not enter the block before its booked
        entry time plus ``minutes``.
    ``block_closure``
        ``{"type": "block_closure", "block_id": "BL3", "start_minute": 20,
        "end_minute": 45}`` -- the block is not available between ``start`` and
        ``end`` (signal failure, track possession, ...).
    """
    dtype = str(raw.get("type") or "signal_delay").strip().lower()

    if dtype in ("delay", "signal_delay", "speed_restriction"):
        train_id = raw.get("train_id")
        block_id = raw.get("block_id")
        minutes = raw.get("minutes", raw.get("delay_minutes"))
        if train_id not in TRAIN_BY_ID:
            raise ValueError(f"unknown train '{train_id}' (expected one of {BOOKED_ORDER})")
        if block_id not in BLOCK_BY_ID:
            raise ValueError(f"unknown block '{block_id}' (expected one of {ROUTE_BLOCK_IDS})")
        try:
            minutes = int(minutes)
        except (TypeError, ValueError):
            raise ValueError("'minutes' must be an integer between 1 and 180") from None
        if not 1 <= minutes <= 180:
            raise ValueError("'minutes' must be between 1 and 180")
        return {
            "type": "signal_delay",
            "train_id": train_id,
            "block_id": block_id,
            "minutes": minutes,
            "label": f"{train_id} +{minutes} min in {block_id}",
            "detail": (
                f"{train_id} may not enter {block_id} before "
                f"{format_minute(_BOOKED_ENTRIES_LAZY()[train_id][block_id] + minutes)}."
            ),
        }

    if dtype in ("closure", "block_closure", "track_closure", "maintenance"):
        block_id = raw.get("block_id")
        if block_id not in BLOCK_BY_ID:
            raise ValueError(f"unknown block '{block_id}' (expected one of {ROUTE_BLOCK_IDS})")
        start = raw.get("start_minute", raw.get("start"))
        end = raw.get("end_minute", raw.get("end"))
        try:
            start, end = int(start), int(end)
        except (TypeError, ValueError):
            raise ValueError("'start_minute' and 'end_minute' must be integers") from None
        if start < 0 or end <= start or end > HORIZON_MIN:
            raise ValueError("'start_minute' must be >= 0 and 'end_minute' > start_minute")
        reason = str(raw.get("reason") or "Track possession / signal failure")
        return {
            "type": "block_closure",
            "block_id": block_id,
            "start": start,
            "end": end,
            "reason": reason,
            "label": f"{block_id} closed {format_minute(start)}-{format_minute(end)}",
            "detail": (
                f"No occupancy of {block_id} {format_minute(start)}-{format_minute(end)}."
            ),
        }

    raise ValueError(f"unknown disruption type '{dtype}'")


def closures_on(disruptions: Sequence[Dict[str, Any]], block_id: str) -> List[Dict[str, Any]]:
    return [
        d for d in disruptions
        if d["type"] == "block_closure" and d["block_id"] == block_id
    ]


def signal_delay_bound(
    disruptions: Sequence[Dict[str, Any]], train_id: str, block_id: str, booked_entry: int
) -> int:
    """Lowest feasible entry time for ``train_id`` entering ``block_id``."""
    lower = booked_entry
    for disruption in disruptions:
        if (
            disruption["type"] == "signal_delay"
            and disruption["train_id"] == train_id
            and disruption["block_id"] == block_id
        ):
            lower = max(lower, booked_entry + disruption["minutes"])
    return lower


def _apply_closure(entry: int, run: int, disruption: Dict[str, Any]) -> int:
    """Push an entry later so the block is clear during a possession window."""
    start, end = disruption["start"], disruption["end"]
    if entry + run <= start or entry >= end:
        return entry  # fits before the window, or already after it
    return max(entry, end)

# ---------------------------------------------------------------------------
# Rule based planning: booked timetable + fallback ("rule engine") plan
# ---------------------------------------------------------------------------

_BASELINE_ENTRY_CACHE: Optional[Dict[str, Dict[str, int]]] = None


def _BOOKED_ENTRIES_LAZY() -> Dict[str, Dict[str, int]]:
    """Late accessor used by the disruption normaliser for readable labels."""
    return build_baseline_entries()


def build_baseline_entries(force: bool = False) -> Dict[str, Dict[str, int]]:
    """Booked block entry times -- generated once and cached (deterministic)."""
    global _BASELINE_ENTRY_CACHE
    if _BASELINE_ENTRY_CACHE is None or force:
        _BASELINE_ENTRY_CACHE = _plan_entries([], compress_dwell=False, booked=None)
    return copy.deepcopy(_BASELINE_ENTRY_CACHE)


def _plan_entries(
    disruptions: Sequence[Dict[str, Any]],
    compress_dwell: bool = False,
    booked: Optional[Dict[str, Dict[str, int]]] = None,
) -> Dict[str, Dict[str, int]]:
    """First come / first served planner used by the rule engine.

    Trains are planned in their booked order.  Every physical constraint is
    enforced (minimum headway per block, minimum station dwell, no running ahead
    of the booked path, disruption bounds) so the plan is always conflict free.
    """
    if booked is None and disruptions:
        raise ValueError("the booked baseline plan cannot carry disruptions")

    block_last_exit: Dict[str, Optional[int]] = {block_id: None for block_id in ROUTE_BLOCK_IDS}
    entries: Dict[str, Dict[str, int]] = {}

    for train in TRAINS:
        train_id = train["id"]
        train_entries: Dict[str, int] = {}
        previous_exit: Optional[int] = None

        for index, block_id in enumerate(ROUTE_BLOCK_IDS):
            run = train["run_min"][block_id]
            if index == 0:
                lower = train["departure"]
            else:
                station_id = STATIONS[index]["id"]
                dwell_floor = MIN_DWELL_MIN if compress_dwell else train["dwell_min"][station_id]
                lower = previous_exit + dwell_floor

            if booked is not None:
                booked_entry = booked[train_id][block_id]
                lower = max(lower, booked_entry)  # never run ahead of the booked path
                lower = max(
                    lower, signal_delay_bound(disruptions, train_id, block_id, booked_entry)
                )

            if block_last_exit[block_id] is not None:
                lower = max(lower, block_last_exit[block_id] + MIN_HEADWAY_MIN)

            for closure in closures_on(disruptions, block_id):
                lower = _apply_closure(lower, run, closure)

            train_entries[block_id] = lower
            previous_exit = lower + run
            block_last_exit[block_id] = previous_exit

        entries[train_id] = train_entries

    return entries


def plan_rule_based(
    disruptions: Sequence[Dict[str, Any]] = (),
    compress_dwell: bool = False,
    source: str = "rule_based",
    booked: Optional[Dict[str, Dict[str, int]]] = None,
) -> Dict[str, Any]:
    """Rule engine plan (deterministic, conflict free) used as the benchmark."""
    booked = build_baseline_entries() if booked is None else booked
    entries = _plan_entries(disruptions, compress_dwell=compress_dwell, booked=booked)
    schedule = schedule_from_entries(entries, source=source, baseline_entries=booked)
    schedule["notes"] = [
        "Rule engine plan: first come / first served, all safety constraints enforced."
    ]
    return schedule


def build_baseline() -> Dict[str, Any]:
    """The booked corridor timetable (conflict free by construction)."""
    booked = build_baseline_entries()
    schedule = schedule_from_entries(booked, source="baseline", baseline_entries=booked)
    schedule["notes"] = ["Booked corridor timetable - conflict free by construction."]
    return schedule

# ---------------------------------------------------------------------------
# Legacy cascade: single hop delay propagation ("no intervention" scenario)
# ---------------------------------------------------------------------------

def _shift_from(train_entries: Dict[str, int], start_index: int, delta: int) -> None:
    """Shift every block entry from ``start_index`` onwards by ``delta`` minutes."""
    for block_id in ROUTE_BLOCK_IDS[start_index:]:
        train_entries[block_id] += delta


def next_booked_train(train_id: str) -> Optional[str]:
    """The train booked immediately behind ``train_id`` on the corridor."""
    index = BOOKED_ORDER.index(train_id)
    return BOOKED_ORDER[index + 1] if index + 1 < len(BOOKED_ORDER) else None


def propagate_legacy(
    disruptions: Sequence[Dict[str, Any]] = (),
    booked: Optional[Dict[str, Dict[str, int]]] = None,
) -> Dict[str, Any]:
    """Legacy cascade: linear, **single hop** delay propagation.

    Delay inheritance follows the explicit dispatcher rule

    ``new_delay = max(0, min_gap - (other_train_time - (delayed_train_time + N)))``

    where ``other_train_time`` is the follower's booked entry into the affected
    block and ``delayed_train_time + N`` is the *revised* moment at which the
    disrupted train clears that block (``N`` = its block running time).

    Only the immediate booked follower reacts, so trains two or more hops
    downstream keep their booked path.  That omission is precisely why the
    cascade plan still contains conflicts and why the CP-SAT re-plan is needed.
    """
    booked = build_baseline_entries() if booked is None else booked
    entries = copy.deepcopy(booked)
    notes: List[str] = []

    for disruption in disruptions:
        if disruption["type"] == "signal_delay":
            train_id = disruption["train_id"]
            block_id = disruption["block_id"]
            minutes = disruption["minutes"]
            index = ROUTE_BLOCK_IDS.index(block_id)
            run = TRAIN_BY_ID[train_id]["run_min"][block_id]

            _shift_from(entries[train_id], index, minutes)
            revised_exit = booked[train_id][block_id] + minutes + run
            notes.append(
                f"{train_id} clears {block_id} {format_minute(revised_exit)} "
                f"(booked {format_minute(booked[train_id][block_id] + run)})."
            )

            follower_id = next_booked_train(train_id)
            if follower_id:
                other_train_time = booked[follower_id][block_id]
                deficit = max(0, MIN_HEADWAY_MIN - (other_train_time - revised_exit))
                if deficit > 0:
                    _shift_from(entries[follower_id], index, deficit)
                    notes.append(
                        f"{follower_id} +{deficit} min behind {train_id}; headway "
                        f"restored {format_minute(revised_exit + MIN_HEADWAY_MIN)}."
                    )
                else:
                    notes.append(
                        f"{follower_id} keeps booked path - headway to {train_id} holds."
                    )
        else:  # block closure
            block_id = disruption["block_id"]
            start, end = disruption["start"], disruption["end"]
            index = ROUTE_BLOCK_IDS.index(block_id)
            affected: List[str] = []

            for train_id in BOOKED_ORDER:
                run = TRAIN_BY_ID[train_id]["run_min"][block_id]
                entry = entries[train_id][block_id]
                if entry + run <= start or entry >= end:
                    continue  # passes before the possession window
                _shift_from(entries[train_id], index, end - entry)
                affected.append(train_id)

            if affected:
                                notes.append(
                    f"{block_id} closed {format_minute(start)}-{format_minute(end)}: "
                    f"{', '.join(affected)} re-planned at {format_minute(end)}."
                )
            else:
                                notes.append(
                    f"{block_id} closed {format_minute(start)}-{format_minute(end)}: "
                    "no booked train affected."
                )

    schedule = schedule_from_entries(entries, source="legacy_cascade", baseline_entries=booked)
    schedule["notes"] = notes
    return schedule

